// Generates the small hand-authored Lottie animations used on the site.
// Output is written as JS files (window.LOTTIE_DATA[name] = {...}) so the
// animations also work when index.html is opened straight from the file system.
// Run: node tools/build-lottie.mjs
import fs from 'node:fs';
import path from 'node:path';

const OUT = path.resolve('assets/lottie');
fs.mkdirSync(OUT, { recursive: true });

const S = (k) => ({ a: 0, k });
const COLOR = [0.478, 0.635, 1, 1]; // #7aa2ff, overridden by CSS per theme
const ease = { i: { x: [0.2], y: [1] }, o: { x: [0.6], y: [0] } };

const line = (...pts) => ({
  ty: 'sh',
  ks: S({ i: pts.map(() => [0, 0]), o: pts.map(() => [0, 0]), v: pts, c: false }),
});
const ellipse = (x, y, w, h = w) => ({ ty: 'el', p: S([x, y]), s: S([w, h]), d: 1 });
const stroke = (w = 2.5) => ({ ty: 'st', c: S(COLOR), o: S(100), w: S(w), lc: 2, lj: 2, ml: 4 });
const fill = () => ({ ty: 'fl', c: S(COLOR), o: S(100), r: 1 });
const tr = (extra = {}) => ({
  ty: 'tr', p: S([0, 0]), a: S([0, 0]), s: S([100, 100]), r: S(0), o: S(100), sk: S(0), sa: S(0), ...extra,
});
const trim = (start, end) => ({
  ty: 'tm', s: S(0), o: S(0), m: 1,
  e: { a: 1, k: [{ t: start, s: [0], ...ease }, { t: end, s: [100] }] },
});

const group = (shapes, { from = 0, to = 40, w = 2.5, fillIt = false, transform } = {}) => ({
  ty: 'gr',
  it: [...shapes, ...(fillIt ? [fill()] : [trim(from, to), stroke(w)]), transform || tr()],
});

const layer = (groups, op) => ({
  ddd: 0, ind: 1, ty: 4, nm: 'art', sr: 1, ao: 0, ip: 0, op, st: 0, bm: 0,
  ks: { o: S(100), r: S(0), p: S([32, 32, 0]), a: S([32, 32, 0]), s: S([100, 100, 100]) },
  shapes: groups,
});

const anim = (name, groups, op = 60) => ({
  v: '5.7.4', fr: 60, ip: 0, op, w: 64, h: 64, nm: name, ddd: 0, assets: [], layers: [layer(groups, op)],
});

const polar = (r, deg) => [32 + r * Math.cos((deg * Math.PI) / 180), 32 + r * Math.sin((deg * Math.PI) / 180)];

const files = {
  // Photography: a lens aperture whose blades draw in after the ring.
  aperture: anim('aperture', [
    group([ellipse(32, 32, 46)], { from: 0, to: 34 }),
    group(
      [0, 60, 120, 180, 240, 300].map((a) => line(polar(23, a), polar(9, a + 100))),
      { from: 14, to: 50 },
    ),
  ]),
  // Travel: a map pin.
  pin: anim('pin', [
    group([{
      ty: 'sh',
      ks: S({
        v: [[32, 57], [14, 27], [32, 8], [50, 27]],
        i: [[0, 0], [0, 12], [-10, 0], [0, -10]],
        o: [[0, 0], [0, -10], [10, 0], [0, 12]],
        c: true,
      }),
    }], { from: 0, to: 40 }),
    group([ellipse(32, 26, 13)], { from: 20, to: 50 }),
  ]),
  // Typography: a serifed capital A.
  letter: anim('letter', [
    group([line([13, 52], [32, 10], [51, 52])], { from: 0, to: 36 }),
    group([line([20, 38], [44, 38])], { from: 18, to: 44 }),
    group([line([8, 52], [19, 52]), line([45, 52], [56, 52])], { from: 30, to: 52 }),
  ]),
  // Jazz: two beamed eighth notes.
  notes: anim('notes', [
    group([ellipse(19, 48, 15, 11), ellipse(43, 44, 15, 11)], { from: 0, to: 30 }),
    group([line([26, 47], [26, 14]), line([50, 43], [50, 10])], { from: 14, to: 40 }),
    group([line([26, 14], [50, 10])], { from: 30, to: 54 }, ),
  ]),
  // Contact form: confirmation tick.
  success: anim('success', [
    group([ellipse(32, 32, 50)], { from: 0, to: 30, w: 3 }),
    group([line([20, 33], [28.5, 41.5], [45, 24])], { from: 22, to: 46, w: 3 }),
  ]),
  // Hero: scroll cue, a mouse outline with a falling dot (looped).
  scroll: {
    ...anim('scroll', [], 90),
    layers: [layer([
      { ty: 'gr', it: [{ ty: 'rc', p: S([32, 32]), s: S([22, 36]), r: S(11), d: 1 }, stroke(2.2), tr()] },
      {
        ty: 'gr',
        it: [
          ellipse(32, 22, 4.5), fill(),
          tr({
            p: { a: 1, k: [{ t: 0, s: [0, 0], ...ease }, { t: 60, s: [0, 12] }, { t: 90, s: [0, 12] }] },
            o: { a: 1, k: [{ t: 0, s: [100], ...ease }, { t: 60, s: [0] }, { t: 90, s: [0] }] },
          }),
        ],
      },
    ], 90)],
  },
};

let js = '// Generated by tools/build-lottie.mjs. Do not edit by hand.\nwindow.LOTTIE_DATA = ';
js += JSON.stringify(files) + ';\n';
fs.writeFileSync(path.join(OUT, 'animations.js'), js);
for (const [name, data] of Object.entries(files)) {
  fs.writeFileSync(path.join(OUT, `${name}.json`), JSON.stringify(data));
}
console.log('wrote', Object.keys(files).join(', '));

